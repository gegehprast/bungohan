function contractClass(
  contract: CodegenModel["contracts"][number],
  cls: string,
  messageClass: (def: MessageDef) => string,
): string[] {
  const table = (defs: readonly MessageDef[]): string[] =>
    defs.map(
      (def) =>
        `        [${literal(def.name)}] = ${messageClass(def)}.Definition,`,
    )
  const decoder = (side: string, defs: readonly MessageDef[]): string[] => [
    `    /// <summary>Decodes a ${side} message by name (resolved from its id through the handshake's table).</summary>`,
    `    public static Result<IContractMessage> Decode${side === "client" ? "Client" : "Server"}(IStateCodec codec, string name, byte[] body)`,
    "    {",
    "        switch (name)",
    "        {",
    ...defs.flatMap((def) => [
      `            case ${literal(def.name)}:`,
      "            {",
      `                var decoded = ${messageClass(def)}.Decode(codec, body);`,
      "                return decoded.IsOk ? Result<IContractMessage>.Ok(decoded.Value) : Result<IContractMessage>.Fail(decoded.Error!);",
      "            }",
    ]),
    "            default:",
    `                return Result<IContractMessage>.Fail(ErrorCodes.DecodeFailed, "no ${side} message named " + name);`,
    "        }",
    "    }",
  ]
  return [
    `/// <summary>Contract <c>${escapeXml(contract.name)}</c>.</summary>`,
    `public static class ${cls}`,
    "{",
    "    /// <summary>",
    "    /// The contract hash this client was built against: sent in JOIN and",
    "    /// compared with the handshake's. Message ids are not generated: they",
    "    /// come from the handshake and are resolved by name.",
    "    /// </summary>",
    `    public const string Hash = ${literal(contract.hash)};`,
    "",
    "    /// <summary>Client → server messages, by name.</summary>",
    "    public static readonly IReadOnlyDictionary<string, MessageDef> ClientMessages = new Dictionary<string, MessageDef>",
    "    {",
    ...table(contract.client),
    "    };",
    "",
    "    /// <summary>Server → client messages, by name.</summary>",
    "    public static readonly IReadOnlyDictionary<string, MessageDef> ServerMessages = new Dictionary<string, MessageDef>",
    "    {",
    ...table(contract.server),
    "    };",
    "",
    ...decoder("server", contract.server),
    "",
    ...decoder("client", contract.client),
    "}",
  ]
}

