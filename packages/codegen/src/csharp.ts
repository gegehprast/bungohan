const SCHEMA_RESERVED = [
  "Class",
  "Definition",
  "SchemaName",
  "ApplyField",
  "GetChild",
  "Apply",
  "Equals",
  "GetHashCode",
  "ToString",
  "GetType",
  "MemberwiseClone",
  "Finalize",
  "ReferenceEquals",
]

function schemaClass(
  schema: SchemaModel,
  className: (name: string) => string,
): string[] {
  const cls = className(schema.name)
  const taken = new Set([cls, ...SCHEMA_RESERVED])
  const members = schema.fields.map((field) => claim(pascal(field.name), taken))
  const lines: string[] = [
    `/// <summary>Schema class <c>${escapeXml(schema.name)}</c>.</summary>`,
    `public sealed partial class ${cls} : Schema`,
    "{",
    `    /// <summary>The class's name on the wire.</summary>`,
    `    public const string SchemaName = ${literal(schema.name)};`,
    "",
    "    /// <summary>Fields and type strings, matched by name against the server's DEFINE.</summary>",
    `    public static readonly SchemaClass Definition = new SchemaClass(SchemaName, () => new ${cls}()${schema.fields.length > 0 ? "," : ");"}`,
  ]
  schema.fields.forEach((field, i) => {
    const last = i === schema.fields.length - 1
    lines.push(
      `        new SchemaField(${literal(field.name)}, ${literal(field.type)})${last ? ");" : ","}`,
    )
  })
  lines.push("", "    public override SchemaClass Class => Definition;")

  const applies: string[] = []
  const children: string[] = []
  schema.fields.forEach((field, i) => {
    const member = members[i] ?? ""
    const parsed = parseFieldType(field.type)
    if (parsed === undefined) {
      throw new CodegenError(
        `${schema.name}.${field.name}: bad type ${field.type}`,
      )
    }
    const doc = `/// <summary><c>${escapeXml(field.name)}</c>: <c>${escapeXml(field.type)}</c>.</summary>`
    lines.push("")
    if (parsed.kind === "primitive" || parsed.kind === "int") {
      const type = scalar(parsed.type)
      const backing = `_${member.charAt(0).toLowerCase()}${member.slice(1)}`
      const event = claim(`${member}Changed`, taken)
      const zero = type === "string" ? ' = ""' : ""
      lines.push(
        `    private ${type} ${backing}${zero};`,
        "",
        `    ${doc}`,
        `    public ${type} ${member} => ${backing};`,
        "",
        `    /// <summary>${member} changed: (value, previous), after the frame is applied.</summary>`,
        `    public event Action<${type}, ${type}>? ${event};`,
      )
      applies.push(
        `${i} => Apply(${i}, ref ${backing}, wire, changes, ${event}),`,
      )
      return
    }
    let type: string
    switch (parsed.kind) {
      case "schema":
        type = className(parsed.schema)
        break
      case "map":
        type = `MapSchema<${scalar(parsed.key)}, ${scalar(parsed.element)}>`
        break
      case "set":
        type = `SetSchema<${scalar(parsed.element)}>`
        break
      case "array":
        type = `ArraySchema<${scalar(parsed.element)}>`
        break
      case "schemaMap":
        type = `MapSchema<${scalar(parsed.key)}, ${className(parsed.schema)}>`
        break
      case "schemaSet":
        type = `SetSchema<${className(parsed.schema)}>`
        break
      default:
        type = `ArraySchema<${className(parsed.schema)}>`
    }
    const init =
      parsed.kind === "schema"
        ? `new ${type}()`
        : `new ${type}(${literal(field.type)})`
    lines.push(`    ${doc}`, `    public ${type} ${member} { get; } = ${init};`)
    children.push(`${i} => ${member},`)
  })

  lines.push(
    "",
    "    protected override bool ApplyField(int index, object? wire, ChangeQueue? changes) => index switch",
    "    {",
    ...applies.map((line) => `        ${line}`),
    "        _ => false,",
    "    };",
    "",
    "    protected override object? GetChild(int index) => index switch",
    "    {",
    ...children.map((line) => `        ${line}`),
    "        _ => null,",
    "    };",
    "}",
  )
  return lines
}

function registry(model: CodegenModel, className: (name: string) => string) {
  return [
    "/// <summary>Every generated schema class.</summary>",
    "public static class Schemas",
    "{",
    "    /// <summary>Registers every class, so the replica can instantiate what the server sends.</summary>",
    "    public static SchemaRegistry Register(SchemaRegistry registry)",
    "    {",
    ...model.schemas.map(
      (schema) =>
        `        registry.Register(${className(schema.name)}.Definition);`,
    ),
    "        return registry;",
    "    }",
    "",
    "    public static SchemaRegistry CreateRegistry() => Register(new SchemaRegistry());",
    "}",
  ]
}

