const MESSAGE_RESERVED = [
  "MessageName",
  "Definition",
  "MessageDefinition",
  "ToPayload",
  "FromPayload",
  "Encode",
  "Decode",
  "Equals",
  "GetHashCode",
  "ToString",
  "GetType",
  "MemberwiseClone",
  "Finalize",
  "ReferenceEquals",
]

/** A C# enum generated for a string enum field. */
interface EnumPlan {
  readonly type: string
  readonly valuesField: string
  readonly members: readonly string[]
  readonly values: readonly EnumValue[]
}

function enumOf(field: Field): Extract<Field, { kind: "enum" }> | undefined {
  switch (field.kind) {
    case "enum":
      return field
    case "array":
    case "map":
    case "optional":
      return enumOf(field.of)
    default:
      return undefined
  }
}

/** The layout grammar of spec §6.7.4, for doc comments. */
export function typeText(field: Field): string {
  switch (field.kind) {
    case "fixed":
      return `fixed:${field.decimals}`
    case "enum":
      return `enum[${field.values.map((v) => JSON.stringify(v)).join("|")}]`
    case "array":
    case "map":
    case "optional":
      return `${field.kind}<${typeText(field.of)}>`
    case "nested":
      return `nested<${field.message.name}>`
    default:
      return field.kind
  }
}

function escapeXml(text: string): string {
  return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
}

class MessageEmitter {
  private readonly _enums = new Map<Field, EnumPlan>()
  private readonly _taken: Set<string>

  public constructor(
    private readonly def: MessageDef,
    private readonly className: (def: MessageDef) => string,
  ) {
    this._taken = new Set([className(def), ...MESSAGE_RESERVED])
  }

  public emit(): string[] {
    const def = this.def
    const cls = this.className(def)
    const names = def.fieldNames.map((name) => claim(pascal(name), this._taken))
    const lines: string[] = []
    const fieldLines: string[] = []
    def.fieldNames.forEach((name, i) => {
      const field = def.fields[name]
      if (field === undefined) return
      const member = names[i] ?? ""
      this._planEnum(field, member)
      const optional = field.kind === "optional"
      const type = optional ? `${this._type(field.of)}?` : this._type(field)
      const init = optional ? "" : this._default(field)
      fieldLines.push(
        "",
        `    /// <summary><c>${escapeXml(name)}</c>: <c>${escapeXml(typeText(field))}</c>.</summary>`,
        `    public ${type} ${member} { get; set; }${init === "" ? "" : ` = ${init};`}`,
      )
    })

    lines.push(
      `/// <summary>Contract message <c>${escapeXml(def.name)}</c>.</summary>`,
      `public sealed partial class ${cls} : IContractMessage`,
      "{",
      "    /// <summary>The message's name on the wire; its id comes from the handshake.</summary>",
      `    public const string MessageName = ${literal(def.name)};`,
      "",
      "    /// <summary>The declaration the codecs encode with.</summary>",
      `    public static readonly MessageDef Definition = new MessageDef(MessageName${def.fieldNames.length > 0 ? "," : ");"}`,
    )
    def.fieldNames.forEach((name, i) => {
      const field = def.fields[name]
      if (field === undefined) return
      const last = i === def.fieldNames.length - 1
      lines.push(
        `        new MessageField(${literal(name)}, ${this._fieldType(field)})${last ? ");" : ","}`,
      )
    })
    for (const plan of this._enums.values()) {
      lines.push(
        "",
        `    /// <summary>The values of <see cref="${plan.type}"/>, in index order.</summary>`,
        `    private static readonly object[] ${plan.valuesField} = { ${plan.values.map((v) => (typeof v === "string" ? literal(v) : String(v))).join(", ")} };`,
        "",
        `    public enum ${plan.type}`,
        "    {",
        ...plan.members.flatMap((member, i) => [
          `        /// <summary><c>${escapeXml(JSON.stringify(plan.values[i]))}</c></summary>`,
          `        ${member} = ${i},`,
        ]),
        "    }",
      )
    }
    lines.push(...fieldLines)

    lines.push(
      "",
      "    MessageDef IContractMessage.MessageDefinition => Definition;",
      "",
      "    public MsgMap ToPayload()",
      "    {",
      "        var payload = new MsgMap();",
    )
    def.fieldNames.forEach((name, i) => {
      const field = def.fields[name]
      if (field === undefined) return
      const member = names[i] ?? ""
      if (field.kind === "optional") {
        const value = this._isValueType(field.of) ? `${member}.Value` : member
        lines.push(
          `        if (${member} != null) payload[${literal(name)}] = ${this._to(field.of, value, 0)};`,
        )
      } else {
        lines.push(
          `        payload[${literal(name)}] = ${this._to(field, member, 0)};`,
        )
      }
    })
    lines.push(
      "        return payload;",
      "    }",
      "",
      `    public static ${cls} FromPayload(MsgMap payload)`,
      "    {",
      `        var message = new ${cls}();`,
    )
    def.fieldNames.forEach((name, i) => {
      const field = def.fields[name]
      if (field === undefined) return
      const member = names[i] ?? ""
      if (field.kind === "optional") {
        const v = `v${i}`
        lines.push(
          `        message.${member} = payload.TryGetValue(${literal(name)}, out object? ${v}) && ${v} != null`,
          `            ? (${this._type(field.of)}?)${this._from(field.of, v, 0)}`,
          "            : null;",
        )
      } else {
        lines.push(
          `        message.${member} = ${this._from(field, `payload[${literal(name)}]`, 0)};`,
        )
      }
    })
    lines.push(
      "        return message;",
      "    }",
      "",
      "    /// <summary>Encodes with the room's codec.</summary>",
      "    public Result<byte[]> Encode(IStateCodec codec) => codec.EncodeMessage(Definition, ToPayload());",
      "",
      "    /// <summary>Decodes a body with the room's codec.</summary>",
      `    public static Result<${cls}> Decode(IStateCodec codec, byte[] body)`,
      "    {",
      "        Result<MsgMap> decoded = codec.DecodeMessage(Definition, body, 0, body.Length);",
      `        return decoded.IsOk ? Result<${cls}>.Ok(FromPayload(decoded.Value)) : Result<${cls}>.Fail(decoded.Error!);`,
      "    }",
      "}",
    )
    return lines
  }

  private _planEnum(field: Field, member: string): void {
    const found = enumOf(field)
    if (found === undefined) return
    const values = found.values
    if (!values.every((v) => typeof v === "string")) return
    const taken = new Set<string>()
    const members = values.map((v) => pascal(v))
    const unique = members.every((m) => !taken.has(m) && taken.add(m))
    if (!unique) return
    this._enums.set(found, {
      type: claim(`${member}Value`, this._taken),
      valuesField: claim(
        `s_${member.charAt(0).toLowerCase()}${member.slice(1)}Values`,
        this._taken,
      ),
      members,
      values,
    })
  }

  private _isValueType(field: Field): boolean {
    switch (field.kind) {
      case "string":
      case "array":
      case "map":
      case "optional":
      case "nested":
        return false
      case "enum":
        return (
          this._enums.has(field) ||
          field.values.every((v) => typeof v === "number")
        )
      default:
        return true
    }
  }

  private _type(field: Field): string {
    switch (field.kind) {
      case "fixed":
        return "double"
      case "enum": {
        const plan = this._enums.get(field)
        if (plan !== undefined) return plan.type
        if (field.values.every((v) => typeof v === "number")) return "double"
        if (field.values.every((v) => typeof v === "string")) return "string"
        return "object"
      }
      case "array":
        return `List<${this._type(field.of)}>`
      case "map":
        return `Dictionary<string, ${this._type(field.of)}>`
      case "optional":
        return `${this._type(field.of)}?`
      case "nested":
        return this.className(field.message)
      default:
        return scalar(field.kind)
    }
  }

  private _default(field: Field): string {
    switch (field.kind) {
      case "string":
        return '""'
      case "array":
      case "map":
      case "nested":
        return `new ${this._type(field)}()`
      case "enum": {
        const type = this._type(field)
        if (type === "string" || type === "object") {
          return literal(String(field.values[0] ?? ""))
        }
        return ""
      }
      default:
        return ""
    }
  }

  /** The Bungohan.Protocol FieldType expression of a field. */
  private _fieldType(field: Field): string {
    switch (field.kind) {
      case "fixed":
        return `FieldType.Fixed(${field.decimals})`
      case "enum":
        return `FieldType.Enum(${field.values.map((v) => (typeof v === "string" ? literal(v) : `${v}d`)).join(", ")})`
      case "array":
        return `FieldType.ArrayOf(${this._fieldType(field.of)})`
      case "map":
        return `FieldType.MapOf(${this._fieldType(field.of)})`
      case "optional":
        return `FieldType.OptionalOf(${this._fieldType(field.of)})`
      case "nested":
        return `FieldType.NestedOf(${this.className(field.message)}.Definition)`
      default:
        return `FieldType.${pascal(field.kind).replace("Uint", "UInt")}`
    }
  }

  /** Member value → payload value (object?). */
  private _to(field: Field, expr: string, depth: number): string {
    const x = `x${depth}`
    switch (field.kind) {
      case "enum": {
        const plan = this._enums.get(field)
        return plan === undefined ? expr : `${plan.valuesField}[(int)${expr}]`
      }
      case "array":
        return `Payloads.FromList(${expr}, ${x} => (object?)${this._to(field.of, x, depth + 1)})`
      case "map":
        return `Payloads.FromMap(${expr}, ${x} => (object?)${this._to(field.of, x, depth + 1)})`
      case "optional":
        return this._isValueType(field.of)
          ? `(${expr}.HasValue ? (object?)${this._to(field.of, `${expr}.Value`, depth)} : null)`
          : `(${expr} == null ? null : (object?)${this._to(field.of, expr, depth)})`
      case "nested":
        return `${expr}.ToPayload()`
      default:
        return expr
    }
  }

  /** Payload value (object?) → member value. */
  private _from(field: Field, expr: string, depth: number): string {
    const x = `x${depth}`
    switch (field.kind) {
      case "int8":
      case "int16":
      case "int32":
      case "uint8":
      case "uint16":
      case "uint32":
        return `(${scalar(field.kind)})Payloads.ToLong(${expr})`
      case "float32":
        return `(float)Payloads.ToDouble(${expr})`
      case "float64":
      case "fixed":
        return `Payloads.ToDouble(${expr})`
      case "string":
        return `(${expr} as string ?? "")`
      case "bool":
        return `(${expr} is true)`
      case "enum": {
        const plan = this._enums.get(field)
        if (plan !== undefined) {
          return `(${plan.type})Math.Max(0, Array.IndexOf(${plan.valuesField}, ${expr}))`
        }
        const type = this._type(field)
        if (type === "double") return `Payloads.ToDouble(${expr})`
        if (type === "string") return `(${expr} as string ?? "")`
        return `(${expr} ?? "")`
      }
      case "array":
        return `Payloads.ToList<${this._type(field.of)}>(${expr}, ${x} => ${this._from(field.of, x, depth + 1)})`
      case "map":
        return `Payloads.ToDictionary<${this._type(field.of)}>(${expr}, ${x} => ${this._from(field.of, x, depth + 1)})`
      case "optional":
        return `(${expr} == null ? (${this._type(field.of)}?)null : ${this._from(field.of, expr, depth)})`
      case "nested":
        return `${this.className(field.message)}.FromPayload(Payloads.AsMap(${expr}))`
    }
  }
}

