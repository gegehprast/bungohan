export function generateCSharp(
  model: CodegenModel,
  options: CSharpOptions,
): Map<string, string> {
  // Type names are unique across the namespace.
  const types = new Set(["Schemas"])
  const schemaNames = new Map<string, string>()
  for (const schema of model.schemas) {
    schemaNames.set(schema.name, claim(pascal(schema.name), types))
  }
  const messageNames = new Map<string, string>()
  for (const def of model.messages) {
    messageNames.set(def.name, claim(`${pascal(def.name)}Message`, types))
  }
  const contractNames = new Map<string, string>()
  for (const contract of model.contracts) {
    contractNames.set(contract.name, claim(pascal(contract.name), types))
  }
  const className = (name: string): string => {
    const out = schemaNames.get(name)
    if (out === undefined)
      throw new CodegenError(`unknown schema class ${name}`)
    return out
  }
  const messageClass = (def: MessageDef): string => {
    const out = messageNames.get(def.name)
    if (out === undefined) throw new CodegenError(`unknown message ${def.name}`)
    return out
  }

  const files = new Map<string, string>()
  if (model.schemas.length > 0) {
    files.set(
      "Schemas.cs",
      file(options, [
        ...model.schemas.map((schema) => schemaClass(schema, className)),
        registry(model, className),
      ]),
    )
  }
  if (model.messages.length > 0) {
    files.set(
      "Messages.cs",
      file(
        options,
        model.messages.map((def) =>
          new MessageEmitter(def, messageClass).emit(),
        ),
      ),
    )
  }
  if (model.contracts.length > 0) {
    files.set(
      "Contracts.cs",
      file(
        options,
        model.contracts.map((contract) =>
          contractClass(
            contract,
            contractNames.get(contract.name) ?? "",
            messageClass,
          ),
        ),
      ),
    )
  }
  return files
}
