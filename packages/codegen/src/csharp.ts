/**
 * `--lang csharp`: bindings for the Bungohan.Protocol core
 * (clients/csharp), for Unity and Godot .NET: netstandard2.1, C# 9.
 *
 * - `Schemas.cs`: a class per schema, each primitive field a read-only
 *   property with a `…Changed(value, previous)` event, nested instances and
 *   collections as read-only properties; `Schemas.CreateRegistry()`.
 * - `Messages.cs`: a class per contract message, with `Definition`,
 *   `ToPayload`/`FromPayload` and `Encode`/`Decode` for a codec.
 * - `Contracts.cs`: a static class per contract: its `Hash`, and its
 *   messages by name. Numeric ids are never generated: they come from the
 *   join handshake and are resolved by name (spec §4.2).
 */
import {
  type EnumValue,
  type Field,
  type MessageDef,
  PROTOCOL_VERSION,
  parseFieldType,
} from "@bungohan/types"
import type { CodegenModel, SchemaModel } from "./model"
import { CodegenError } from "./model"
import { claim, pascal } from "./names"

export interface CSharpOptions {
  /** Namespace of the generated code. */
  readonly namespace: string
  /** Shown in the header comment (module names, never absolute paths). */
  readonly source: string
}

const SCALARS: Readonly<Record<string, string>> = {
  int8: "sbyte",
  int16: "short",
  int32: "int",
  uint8: "byte",
  uint16: "ushort",
  uint32: "uint",
  float32: "float",
  float64: "double",
  string: "string",
  bool: "bool",
}

function scalar(type: string): string {
  if (type.startsWith("fixed:")) return "double"
  const out = SCALARS[type]
  if (out === undefined) throw new CodegenError(`no C# type for ${type}`)
  return out
}

function literal(value: string): string {
  return JSON.stringify(value)
}

function header(options: CSharpOptions): string[] {
  return [
    "// <auto-generated>",
    `// Generated by @bungohan/codegen from ${options.source} (${PROTOCOL_VERSION}).`,
    "// Do not edit: regenerate instead.",
    "// </auto-generated>",
    "#nullable enable",
    "using System;",
    "using System.Collections.Generic;",
    "using Bungohan.Protocol;",
    "",
    `namespace ${options.namespace}`,
    "{",
  ]
}

/** Indents every non-empty line by `levels` × 4 spaces. */
function indent(lines: readonly string[], levels = 1): string[] {
  const pad = "    ".repeat(levels)
  return lines.map((line) => (line === "" ? "" : pad + line))
}

function file(options: CSharpOptions, blocks: string[][]): string {
  const body: string[] = []
  blocks.forEach((block, i) => {
    if (i > 0) body.push("")
    body.push(...indent(block))
  })
  return `${[...header(options), ...body, "}"].join("\n")}\n`
}

