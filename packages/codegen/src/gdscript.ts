function literal(value: string): string {
  return JSON.stringify(value)
}

function header(options: GDScriptOptions, extend: string): string[] {
  return [
    `# Generated by @bungohan/codegen from ${options.source} (${PROTOCOL_VERSION}).`,
    "# Do not edit: regenerate instead.",
    `extends ${extend}`,
  ]
}

function text(lines: readonly string[]): string {
  return `${lines.join("\n")}\n`
}

function scalar(type: string): { type: string; zero: string } {
  if (type === "string") return { type: "String", zero: '""' }
  if (type === "bool") return { type: "bool", zero: "false" }
  if (type === "float32" || type === "float64" || type.startsWith("fixed:")) {
    return { type: "float", zero: "0.0" }
  }
  return { type: "int", zero: "0" }
}

