function contractScript(
  contract: CodegenModel["contracts"][number],
  options: GDScriptOptions,
  messageConst: (def: MessageDef) => string,
  messageFile: (def: MessageDef) => string,
): string {
  const defs = [...new Set([...contract.client, ...contract.server])].sort(
    (a, b) => (a.name < b.name ? -1 : 1),
  )
  const table = (list: readonly MessageDef[]): string[] =>
    list.map((def) => `\t${literal(def.name)}: ${messageConst(def)},`)
  return text([
    ...header(options, "RefCounted"),
    `## Contract \`${contract.name}\`.`,
    "",
    `const Result = preload(${literal(`${options.addon}/protocol/result.gd`)})`,
    ...defs.map(
      (def) =>
        `const ${messageConst(def)} = preload(${literal(`../${messageFile(def)}.gd`)})`,
    ),
    "",
    "## The contract hash this client was built against: sent in JOIN and",
    "## compared with the handshake's. Message ids are not generated: they",
    "## come from the handshake and are resolved by name.",
    `const HASH := ${literal(contract.hash)}`,
    "## Client → server messages, by name.",
    "const CLIENT := {",
    ...table(contract.client),
    "}",
    "## Server → client messages, by name.",
    "const SERVER := {",
    ...table(contract.server),
    "}",
    "",
    "",
    "## Decodes a server message by name (resolved from its id through the",
    "## handshake's table): a Result holding the message.",
    "static func decode_server(codec, name: String, body: PackedByteArray):",
    "\treturn _decode(SERVER, codec, name, body)",
    "",
    "",
    "static func decode_client(codec, name: String, body: PackedByteArray):",
    "\treturn _decode(CLIENT, codec, name, body)",
    "",
    "",
    "static func _decode(table: Dictionary, codec, name: String, body: PackedByteArray):",
    "\tif not table.has(name):",
    '\t\treturn Result.failure(Result.DECODE_FAILED, "no message named " + name)',
    "\treturn table[name].decode(codec, body)",
  ])
}

export function generateGDScript(
  model: CodegenModel,
  options: GDScriptOptions,
): Map<string, string> {
  const files = new Map<string, string>()
  const paths = new Set<string>()
  const schemaFiles = new Map<string, string>()
  for (const schema of model.schemas) {
    schemaFiles.set(schema.name, claim(`schemas/${snake(schema.name)}`, paths))
  }
  const messageFiles = new Map<string, string>()
  for (const def of model.messages) {
    messageFiles.set(
      def.name,
      claim(`messages/${snake(def.name)}_message`, paths),
    )
  }
  const contractFiles = new Map<string, string>()
  for (const contract of model.contracts) {
    contractFiles.set(
      contract.name,
      claim(`contracts/${snake(contract.name)}`, paths),
    )
  }
  const schemaFile = (name: string): string => {
    const out = schemaFiles.get(name)
    if (out === undefined)
      throw new CodegenError(`unknown schema class ${name}`)
    return out
  }
  const messageFile = (def: MessageDef): string => {
    const out = messageFiles.get(def.name)
    if (out === undefined) throw new CodegenError(`unknown message ${def.name}`)
    return out
  }
  // Paths relative to the script that preloads them.
  const sibling = (path: string): string => path.slice(path.indexOf("/") + 1)

  for (const schema of model.schemas) {
    files.set(
      `${schemaFile(schema.name)}.gd`,
      schemaScript(schema, options, (name) => sibling(schemaFile(name))),
    )
  }
  for (const def of model.messages) {
    files.set(
      `${messageFile(def)}.gd`,
      new MessageScript(def, options, (d) => sibling(messageFile(d))).emit(),
    )
  }

  // bindings.gd: one const per class.
  const consts = new Set(["SchemaRegistry", "SCHEMAS"])
  const schemaConst = new Map<string, string>()
  for (const schema of model.schemas) {
    schemaConst.set(schema.name, claim(pascal(schema.name), consts))
  }
  const messageConstNames = new Map<string, string>()
  for (const def of model.messages) {
    messageConstNames.set(def.name, claim(`${pascal(def.name)}Message`, consts))
  }
  const messageConst = (def: MessageDef): string =>
    messageConstNames.get(def.name) ?? ""
  const contractConst = new Map<string, string>()
  for (const contract of model.contracts) {
    contractConst.set(contract.name, claim(pascal(contract.name), consts))
  }
  for (const contract of model.contracts) {
    files.set(
      `${contractFiles.get(contract.name) ?? ""}.gd`,
      contractScript(contract, options, messageConst, messageFile),
    )
  }

  const index = [
    ...header(options, "RefCounted"),
    "## Everything generated, preloaded:",
    "##",
    '##     const Bindings = preload("res://…/bindings.gd")',
    "##     var registry = Bindings.create_registry()",
    "",
    `const SchemaRegistry = preload(${literal(`${options.addon}/replica/schema_registry.gd`)})`,
    "",
    ...model.schemas.map(
      (s) =>
        `const ${schemaConst.get(s.name)} = preload(${literal(`${schemaFile(s.name)}.gd`)})`,
    ),
    ...model.messages.map(
      (d) =>
        `const ${messageConst(d)} = preload(${literal(`${messageFile(d)}.gd`)})`,
    ),
    ...model.contracts.map(
      (c) =>
        `const ${contractConst.get(c.name)} = preload(${literal(`${contractFiles.get(c.name)}.gd`)})`,
    ),
    "",
    "## Every schema class.",
    `const SCHEMAS := [${model.schemas.map((s) => schemaConst.get(s.name)).join(", ")}]`,
    "",
    "",
    "## A registry holding every schema class, so the replica can instantiate",
    "## what the server sends.",
    "static func create_registry():",
    "\tvar registry = SchemaRegistry.new()",
    "\tfor schema in SCHEMAS:",
    "\t\tregistry.register(schema)",
    "\treturn registry",
  ]
  files.set("bindings.gd", text(index))
  if (paths.size + 1 !== files.size) {
    throw new CodegenError("generated file names collide")
  }
  return files
}
