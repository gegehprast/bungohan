function schemaScript(
  schema: SchemaModel,
  options: GDScriptOptions,
  fileOf: (name: string) => string,
): string {
  const replica = `${options.addon}/replica`
  const taken = new Set([...RESERVED])
  const members = schema.fields.map((field) => claim(snake(field.name), taken))
  const consts = new Set(["SCHEMA_NAME", "FIELDS"])
  const preloads = new Map<string, string>() // const name → path
  const collectionConst = (kind: string): string => {
    const name =
      kind === "map"
        ? "MapSchema"
        : kind === "set"
          ? "SetSchema"
          : "ArraySchema"
    consts.add(name)
    preloads.set(name, `${replica}/${snake(name)}.gd`)
    return name
  }
  const nestedConst = new Map<string, string>()
  const classConst = (name: string): string => {
    let out = nestedConst.get(name)
    if (out === undefined) {
      out = claim(pascal(name), consts)
      nestedConst.set(name, out)
      preloads.set(out, `${fileOf(name)}.gd`)
    }
    return out
  }

  const signals: string[] = []
  const vars: string[] = []
  schema.fields.forEach((field, i) => {
    const member = members[i] ?? ""
    const parsed = parseFieldType(field.type)
    if (parsed === undefined) {
      throw new CodegenError(
        `${schema.name}.${field.name}: bad type ${field.type}`,
      )
    }
    vars.push(`## \`${field.name}\`: ${field.type}.`)
    if (parsed.kind === "primitive" || parsed.kind === "int") {
      const { type, zero } = scalar(parsed.type)
      const signal = claim(`${member}_changed`, taken)
      signals.push(
        `## \`${field.name}\` changed; emitted after the frame is applied.`,
        `signal ${signal}(value: ${type}, previous: ${type})`,
      )
      vars.push(`var ${member}: ${type} = ${zero}`)
    } else if (parsed.kind === "schema") {
      vars.push(`var ${member} = ${classConst(parsed.schema)}.new()`)
    } else {
      const kind = parsed.kind.replace("schema", "").toLowerCase()
      vars.push(
        `var ${member} = ${collectionConst(kind)}.new(${literal(field.type)})`,
      )
    }
  })

  const lines = [
    ...header(options, literal(`${replica}/schema.gd`)),
    `## Schema class \`${schema.name}\`.`,
    "",
  ]
  for (const [name, path] of [...preloads].sort(([a], [b]) =>
    a < b ? -1 : 1,
  )) {
    lines.push(`const ${name} = preload(${literal(path)})`)
  }
  if (preloads.size > 0) lines.push("")
  lines.push(
    "## The class's name on the wire.",
    `const SCHEMA_NAME := ${literal(schema.name)}`,
    "## [wire name, type, member]: matched by name against the server's DEFINE.",
    "const FIELDS := [",
    ...schema.fields.map(
      (field, i) =>
        `\t[${literal(field.name)}, ${literal(field.type)}, ${literal(members[i] ?? "")}],`,
    ),
    "]",
  )
  if (signals.length > 0) lines.push("", ...signals)
  if (vars.length > 0) lines.push("", ...vars)
  return text(lines)
}

