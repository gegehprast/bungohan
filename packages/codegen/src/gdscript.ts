function isIdentity(field: Field): boolean {
  switch (field.kind) {
    case "nested":
      return false
    case "array":
    case "map":
    case "optional":
      return isIdentity(field.of)
    default:
      return true
  }
}

class MessageScript {
  private readonly _consts = new Set(["Contract", "Payloads", "MESSAGE_NAME"])
  private readonly _nested = new Map<string, string>()
  private readonly _preloads = new Map<string, string>()

  public constructor(
    private readonly def: MessageDef,
    private readonly options: GDScriptOptions,
    private readonly fileOf: (def: MessageDef) => string,
  ) {}

  public emit(): string {
    const def = this.def
    const taken = new Set([
      ...RESERVED,
      "definition",
      "to_payload",
      "from_payload",
      "encode",
      "decode",
    ])
    const members = def.fieldNames.map((name) => claim(snake(name), taken))
    const enumConsts: string[] = []
    const vars: string[] = []
    const toLines: string[] = []
    const fromLines: string[] = []
    const declLines: string[] = []
    def.fieldNames.forEach((name, i) => {
      const field = def.fields[name]
      if (field === undefined) return
      const member = members[i] ?? ""
      declLines.push(`\t\t\t[${literal(name)}, ${this._fieldType(field)}],`)
      const found = findEnum(field)
      if (found !== undefined) {
        const constName = claim(`${upperSnake(member)}_VALUES`, this._consts)
        enumConsts.push(
          `## Values of \`${name}\`, in index order.`,
          `const ${constName} := [${found.values.map((v) => (typeof v === "string" ? literal(v) : String(v))).join(", ")}]`,
        )
      }
      vars.push(`## \`${name}\`: ${typeText(field)}.`)
      if (field.kind === "optional") {
        vars.push(`var ${member} = null`)
        toLines.push(
          `\tif ${member} != null:`,
          `\t\tpayload[${literal(name)}] = ${this._to(field.of, member, 0)}`,
        )
        fromLines.push(
          `\tif payload.get(${literal(name)}) != null:`,
          `\t\tmessage.${member} = ${this._from(field.of, `payload[${literal(name)}]`, 0)}`,
        )
      } else {
        vars.push(`var ${member}${this._typed(field)}`)
        toLines.push(
          `\tpayload[${literal(name)}] = ${this._to(field, member, 0)}`,
        )
        fromLines.push(
          `\tmessage.${member} = ${this._from(field, `payload.get(${literal(name)})`, 0)}`,
        )
      }
    })

    const addon = `${this.options.addon}/protocol`
    const lines = [
      ...header(this.options, "RefCounted"),
      `## Contract message \`${def.name}\`.`,
      "",
      `const Contract = preload(${literal(`${addon}/contract.gd`)})`,
      `const Payloads = preload(${literal(`${addon}/payloads.gd`)})`,
    ]
    for (const [name, path] of [...this._preloads].sort(([a], [b]) =>
      a < b ? -1 : 1,
    )) {
      lines.push(`const ${name} = preload(${literal(path)})`)
    }
    lines.push(
      "",
      "## The message's name on the wire; its id comes from the handshake.",
      `const MESSAGE_NAME := ${literal(def.name)}`,
      ...enumConsts,
      "",
      "static var _definition = null",
    )
    if (vars.length > 0) lines.push("", ...vars)
    lines.push(
      "",
      "",
      "## The declaration the codecs encode with.",
      "static func definition():",
      "\tif _definition == null:",
      `\t\t_definition = Contract.message(MESSAGE_NAME, [`,
      ...declLines,
      "\t\t])",
      "\treturn _definition",
      "",
      "",
      "func to_payload() -> Dictionary:",
      "\tvar payload := {}",
      ...toLines,
      "\treturn payload",
      "",
      "",
      "static func from_payload(payload: Dictionary):",
      "\tvar message = new()",
      ...fromLines,
      "\treturn message",
      "",
      "",
      "## Encodes with the room's codec: a Result holding the bytes.",
      "func encode(codec):",
      "\treturn codec.encode_message(definition(), to_payload())",
      "",
      "",
      "## Decodes a body with the room's codec: a Result holding the message.",
      "static func decode(codec, body: PackedByteArray):",
      "\tvar decoded = codec.decode_message(definition(), body)",
      "\tif decoded.ok:",
      "\t\tdecoded.value = from_payload(decoded.value)",
      "\treturn decoded",
    )
    return text(lines)
  }

  private _nestedConst(def: MessageDef): string {
    let out = this._nested.get(def.name)
    if (out === undefined) {
      out = claim(`${pascal(def.name)}Message`, this._consts)
      this._nested.set(def.name, out)
      this._preloads.set(out, `${this.fileOf(def)}.gd`)
    }
    return out
  }

  private _typed(field: Field): string {
    switch (field.kind) {
      case "array":
        return ": Array = []"
      case "map":
        return ": Dictionary = {}"
      case "nested":
        return ` = ${this._nestedConst(field.message)}.new()`
      case "enum": {
        const first = field.values[0]
        return ` = ${typeof first === "string" ? literal(first) : String(first)}`
      }
      default: {
        const { type, zero } = scalar(
          field.kind === "fixed" ? "fixed:0" : field.kind,
        )
        return `: ${type} = ${zero}`
      }
    }
  }

  private _fieldType(field: Field): string {
    switch (field.kind) {
      case "fixed":
        return `Contract.fixed(${field.decimals})`
      case "enum":
        return `Contract.enum_of([${field.values.map((v) => (typeof v === "string" ? literal(v) : String(v))).join(", ")}])`
      case "array":
        return `Contract.array_of(${this._fieldType(field.of)})`
      case "map":
        return `Contract.map_of(${this._fieldType(field.of)})`
      case "optional":
        return `Contract.optional_of(${this._fieldType(field.of)})`
      case "nested":
        return `Contract.nested(${this._nestedConst(field.message)}.definition())`
      case "bool":
        return "Contract.bool_()"
      default:
        return `Contract.${field.kind}()`
    }
  }

  /** Member value → payload value. */
  private _to(field: Field, expr: string, depth: number): string {
    const x = `x${depth}`
    switch (field.kind) {
      case "array":
        return isIdentity(field.of)
          ? `${expr}.duplicate()`
          : `Payloads.map_list(${expr}, func(${x}): return ${this._to(field.of, x, depth + 1)})`
      case "map":
        return isIdentity(field.of)
          ? `${expr}.duplicate()`
          : `Payloads.map_values(${expr}, func(${x}): return ${this._to(field.of, x, depth + 1)})`
      case "optional":
        return isIdentity(field.of)
          ? expr
          : `(null if ${expr} == null else ${this._to(field.of, expr, depth)})`
      case "nested":
        return `${expr}.to_payload()`
      default:
        return expr
    }
  }

  /** Payload value → member value. */
  private _from(field: Field, expr: string, depth: number): string {
    const x = `x${depth}`
    switch (field.kind) {
      case "array":
        return isIdentity(field.of)
          ? `Payloads.map_list(${expr}, func(${x}): return ${x})`
          : `Payloads.map_list(${expr}, func(${x}): return ${this._from(field.of, x, depth + 1)})`
      case "map":
        return isIdentity(field.of)
          ? `Payloads.map_values(${expr}, func(${x}): return ${x})`
          : `Payloads.map_values(${expr}, func(${x}): return ${this._from(field.of, x, depth + 1)})`
      case "optional":
        return isIdentity(field.of)
          ? expr
          : `(null if ${expr} == null else ${this._from(field.of, expr, depth)})`
      case "nested":
        return `${this._nestedConst(field.message)}.from_payload(${expr})`
      default:
        return expr
    }
  }
}

function findEnum(field: Field): Extract<Field, { kind: "enum" }> | undefined {
  switch (field.kind) {
    case "enum":
      return field
    case "array":
    case "map":
    case "optional":
      return findEnum(field.of)
    default:
      return undefined
  }
}

