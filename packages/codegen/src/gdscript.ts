/**
 * `--lang gdscript`: bindings for the Bungohan Godot addon
 * (clients/godot/addons/bungohan). One script per class, no `class_name`
 * (so nothing collides with the project's own global classes); everything
 * is reached through `bindings.gd`:
 *
 * - `schemas/<name>.gd`: a schema class, a typed var per primitive field
 *   with a `<field>_changed(value, previous)` signal, nested instances and
 *   collections as vars.
 * - `messages/<name>_message.gd`: a contract message, with `definition()`,
 *   `to_payload()`/`from_payload()` and `encode()`/`decode()`.
 * - `contracts/<name>.gd`: a contract's `HASH` and its messages by name.
 *   Numeric ids are never generated (spec §4.2).
 * - `bindings.gd`: preloads everything; `create_registry()`.
 */
